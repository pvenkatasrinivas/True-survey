-- ============================================================
-- True Survey - PostgreSQL schema (reference)
--
-- You do NOT have to run this file: the backend uses
--   spring.jpa.hibernate.ddl-auto=update
-- so Hibernate creates these tables from the @Entity classes on first start.
-- It is here so you can see the structure, or create the tables by hand:
--   psql -U postgres -d truesurvey -f database/schema.sql
--
-- Relationships:
--   surveys 1 --- * questions 1 --- * question_options
--   surveys 1 --- * survey_responses 1 --- * answers
--   answers * --- 1 questions,  answers * --- 0..1 question_options
-- ============================================================

CREATE TABLE IF NOT EXISTS surveys (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(150)  NOT NULL,
    description  VARCHAR(1000),
    created_at   TIMESTAMP     NOT NULL,
    updated_at   TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS questions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id  BIGINT        NOT NULL REFERENCES surveys (id),
    text       VARCHAR(300)  NOT NULL,
    type       VARCHAR(20)   NOT NULL,    -- SHORT_TEXT, SINGLE_CHOICE, MULTIPLE_CHOICE
    required   BOOLEAN       NOT NULL,
    position   INTEGER       NOT NULL     -- 1, 2, 3 ... display order
);

CREATE TABLE IF NOT EXISTS question_options (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id  BIGINT        NOT NULL REFERENCES questions (id),
    text         VARCHAR(150)  NOT NULL,
    position     INTEGER       NOT NULL
);

CREATE TABLE IF NOT EXISTS survey_responses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id     BIGINT     NOT NULL REFERENCES surveys (id),
    submitted_at  TIMESTAMP  NOT NULL
);

-- One row per text answer, one row per selected option
CREATE TABLE IF NOT EXISTS answers (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    response_id  BIGINT         NOT NULL REFERENCES survey_responses (id),
    question_id  BIGINT         NOT NULL REFERENCES questions (id),
    option_id    BIGINT         REFERENCES question_options (id),
    text_value   VARCHAR(1000)
);

CREATE INDEX IF NOT EXISTS idx_questions_survey   ON questions (survey_id);
CREATE INDEX IF NOT EXISTS idx_options_question   ON question_options (question_id);
CREATE INDEX IF NOT EXISTS idx_responses_survey   ON survey_responses (survey_id);
CREATE INDEX IF NOT EXISTS idx_answers_response   ON answers (response_id);
CREATE INDEX IF NOT EXISTS idx_answers_question   ON answers (question_id);
